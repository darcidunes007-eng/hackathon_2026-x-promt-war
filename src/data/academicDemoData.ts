export function buildDemoFallbackQuestions(
  subject: AcademicSubject,
  chapterTitle: string,
  count: number
): AcademicQuestion[] {
  const base: AcademicQuestion[] = [
    {
      id: `q-fallback-1-${Date.now()}`,
      type: 'mcq',
      topic: chapterTitle || subject.name,
      difficulty: 'Intermediate',
      prompt: `In ${subject.name} (${chapterTitle}), which approach best verifies correctness before finalizing a solution?`,
      options: [
        'Check boundary conditions, units/dimensions, and known invariants',
        'Assume the first intermediate calculation holds for all edge cases',
        'Skip checking special cases when formulas look familiar',
        'Ignore constraints outside the main definition',
      ],
      correctOptionIndex: 0,
      explanation:
        'Boundary-condition and invariant checks systematically expose sign errors, domain restrictions, and edge-case failures.',
      aiGenerated: false,
    },
    {
      id: `q-fallback-2-${Date.now()}`,
      type: 'multiple_select',
      topic: chapterTitle || subject.name,
      difficulty: 'Intermediate',
      prompt: `Select the habits that strengthen conceptual mastery in ${chapterTitle || subject.name}:`,
      options: [
        'Deriving core relationships from first principles',
        'Reviewing why incorrect distractors fail',
        'Memorizing isolated answers without checking assumptions',
      ],
      correctOptionIndices: [0, 1],
      explanation:
        'First-principles derivation and error analysis build transferable understanding across unfamiliar problem variations.',
      aiGenerated: false,
    },
    {
      id: `q-fallback-3-${Date.now()}`,
      type: 'short_answer',
      topic: chapterTitle || subject.name,
      difficulty: 'Beginner',
      prompt: `Summarize one core principle from "${chapterTitle || subject.name}" and explain a constraint where it applies.`,
      keyPoints: ['principle', 'condition', 'example'],
      referenceAnswer:
        'State the principle clearly, specify its assumptions or boundary conditions, and connect it to a concrete case.',
      explanation:
        'Explicitly naming assumptions prevents misapplying formulas outside their valid regime.',
      aiGenerated: false,
    },
  ];

  return base.slice(0, Math.max(1, Math.min(count, base.length)));
}
